# OTA password outside the project config (pattern: ~/dev-knowledge/esp32/ota-wifi-upload.md).
#
# ${sysenv.X} in platformio.ini would enter project.checksum — a shell without ~/.secrets/iot.env
# would then wipe the whole .pio/build. Here the password goes to a generated header and to the
# espota flags; compiler flags and the checksum stay constant.
#
# Upload (USB or OTA) without the variable = error (the panel would get an empty password and every
# later OTA would fail with "Authentication Failed"); a plain build only warns.

import os
import shlex

Import("env")

var = env.GetProjectOption("custom_ota_password_var")
password = os.environ.get(var, "")
uploading = any(t in COMMAND_LINE_TARGETS for t in ("upload", "uploadfs"))

if not password:
    if uploading:
        print("\n*** %s not set — upload aborted (source ~/.secrets/iot.env)\n" % var)
        env.Exit(1)
    print("*** WARNING: %s not set — firmware with an empty OTA password (build only)" % var)

gen_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")
header = os.path.join(gen_dir, "ota_secret.h")
escaped = password.replace("\\", "\\\\").replace('"', '\\"')
content = '#pragma once\n// Generated by scripts/ota_secret.py — do not edit\n#define OTA_PASSWORD "%s"\n' % escaped

# Write only on change — constant mtime = no recompilation
old = None
if os.path.isfile(header):
    with open(header, encoding="utf8") as f:
        old = f.read()
if old != content:
    os.makedirs(gen_dir, exist_ok=True)
    with open(header, "w", encoding="utf8") as f:
        f.write(content)

env.Append(CPPPATH=[gen_dir])

if env.subst("$UPLOAD_PROTOCOL") == "espota" and password:
    # The upload command runs through sh: quote it, or ";", "#", "$" etc. split the command and
    # sh prints the rest of the password in its "not found" error.
    env.Append(UPLOAD_FLAGS=[shlex.quote("--auth=" + password)])

    # The platform adds espota --debug after pre-scripts; espota then prints its whole options
    # Namespace including auth='<password>'. Strip it right before the upload runs.
    def _no_espota_debug(source, target, env):
        env.Replace(UPLOADERFLAGS=[f for f in env.get("UPLOADERFLAGS", []) if f != "--debug"])

    env.AddPreAction("upload", _no_espota_debug)
