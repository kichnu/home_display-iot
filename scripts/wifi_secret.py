# Wi-Fi credentials outside the repo (pattern: ~/dev-knowledge/iot-security/secrets-in-firmware.md).
#
# The panel has no FRAM/provisioning: these are its only credentials. Same variables as the lamps
# (IOT_WIFI_FALLBACK_SSID / IOT_WIFI_FALLBACK_PASSWORD in ~/.secrets/iot.env) — one network, and the
# password is also the source of the lamps' ESP-NOW HMAC key (stage 3).
#
# Missing variables: a plain build only warns (panel stays off the network); an upload is aborted.

import os

Import("env")

SSID_VAR = "IOT_WIFI_FALLBACK_SSID"
PASS_VAR = "IOT_WIFI_FALLBACK_PASSWORD"

ssid = os.environ.get(SSID_VAR, "")
password = os.environ.get(PASS_VAR, "")
uploading = any(t in COMMAND_LINE_TARGETS for t in ("upload", "uploadfs"))

if not ssid or not password:
    if uploading:
        print("\n*** %s / %s not set — upload aborted (source ~/.secrets/iot.env)\n" % (SSID_VAR, PASS_VAR))
        env.Exit(1)
    print("*** WARNING: %s / %s not set — firmware without Wi-Fi (build only)" % (SSID_VAR, PASS_VAR))


def c_str(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


gen_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")
header = os.path.join(gen_dir, "wifi_secret.h")
content = (
    "#pragma once\n"
    "// Generated by scripts/wifi_secret.py — do not edit\n"
    "#define WIFI_SSID %s\n"
    "#define WIFI_PASSWORD %s\n" % (c_str(ssid), c_str(password))
)

old = None
if os.path.isfile(header):
    with open(header, encoding="utf8") as f:
        old = f.read()
if old != content:
    os.makedirs(gen_dir, exist_ok=True)
    with open(header, "w", encoding="utf8") as f:
        f.write(content)

env.Append(CPPPATH=[gen_dir])
